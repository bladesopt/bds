function verify_bds_benchmark_workflows()
%VERIFY_BDS_BENCHMARK_WORKFLOWS Verify the core benchmark workflow contracts.
%
%   VERIFY_BDS_BENCHMARK_WORKFLOWS() checks that the acceleration,
%   termination, and invalid-function-evaluation workflows retain the exact
%   S2MPJ dimension ranges, feature sets, solver labels, manual trigger, and
%   artifact-merging structure selected for the production experiments.

tests_dir = fileparts(mfilename('fullpath'));
root_dir = fileparts(tests_dir);
workflow_dir = fullfile(root_dir, '.github', 'workflows');

acceleration_features = ['feature: [plain, noisy_1e-1, noisy_1e-2, ', ...
    'noisy_1e-3, noisy_1e-4, permuted, linearly_transformed, ', ...
    'rotation_noisy_1e-1, rotation_noisy_1e-2, rotation_noisy_1e-3, ', ...
    'rotation_noisy_1e-4]'];
invalid_features = ...
    'feature: [random_nan_5, random_nan_10, random_nan_20]';
competitor_features = ['feature: [plain, perturbed_x0_0.001, ', ...
    'perturbed_x0_1, perturbed_x0_10, perturbed_x0_100, noisy_1e-1, ', ...
    'noisy_1e-2, noisy_1e-3, noisy_1e-4, truncated_1, truncated_2, ', ...
    'truncated_3, truncated_4, permuted, linearly_transformed, ', ...
    'random_nan_5, random_nan_10, random_nan_20, quantized_1, ', ...
    'quantized_2, quantized_3, quantized_4, rotation_noisy_1e-1, ', ...
    'rotation_noisy_1e-2, rotation_noisy_1e-3, rotation_noisy_1e-4]'];

assert_competitor_workflow_set(workflow_dir);
assert_competitor_pair(workflow_dir, 'bfo', 'bfo-500n', ...
    competitor_features);
assert_competitor_pair(workflow_dir, 'nomad', 'nomad-500n', ...
    competitor_features);
assert_nomad_runtime_linking(workflow_dir);
assert_competitor_pair(workflow_dir, 'newuoa', 'newuoa-500n', ...
    competitor_features);
assert_competitor_pair(workflow_dir, 'bfgs_no_gradient', ...
    'bfgs-no-gradient-500n', competitor_features);

assert_workflow_contract( ...
    fullfile(workflow_dir, 'benchmark_bds_acceleration_small.yml'), ...
    1, 5, acceleration_features, { ...
    'bds-acceleration-off-500n', 'bds-acceleration-on-500n'});
assert_workflow_contract( ...
    fullfile(workflow_dir, 'benchmark_bds_acceleration_big.yml'), ...
    6, 50, acceleration_features, { ...
    'bds-acceleration-off-500n', 'bds-acceleration-on-500n'});
termination_workflow_path = ...
    fullfile(workflow_dir, 'benchmark_bds_termination_big.yml');
assert_workflow_contract( ...
    termination_workflow_path, ...
    6, 50, acceleration_features, { ...
    'bds-function-value-stop-500n', ...
    'bds-estimated-gradient-stop-500n', ...
    'bds-combined-stop-500n'});
assert(contains(fileread(termination_workflow_path), 'options.n_runs = 1;'));
assert_workflow_contract( ...
    fullfile(workflow_dir, 'invalid_function_evaluation_test.yml'), ...
    6, 50, invalid_features, { ...
    'bds-invalid-aware-500n', 'bds-simplified-500n'});

fprintf('BDS_BENCHMARK_WORKFLOWS_OK\n');

end

function assert_competitor_workflow_set(workflow_dir)

expected_files = sort({ ...
    'profile_bds_bfgs_no_gradient_big_s2mpj.yml', ...
    'profile_bds_bfgs_no_gradient_small_s2mpj.yml', ...
    'profile_bds_bfo_big_s2mpj.yml', ...
    'profile_bds_bfo_small_s2mpj.yml', ...
    'profile_bds_newuoa_big_s2mpj.yml', ...
    'profile_bds_newuoa_small_s2mpj.yml', ...
    'profile_bds_nomad_big_s2mpj.yml', ...
    'profile_bds_nomad_small_s2mpj.yml'});
workflow_files = dir(fullfile(workflow_dir, 'profile_bds_*.yml'));
actual_files = sort({workflow_files.name});
assert(isequal(actual_files, expected_files), ...
    'The competitor workflow file set must contain only small/big S2MPJ.');

end


function assert_competitor_pair( ...
        workflow_dir, competitor_file_label, competitor_solver_label, features)

assert_workflow_contract(fullfile(workflow_dir, sprintf( ...
    'profile_bds_%s_small_s2mpj.yml', competitor_file_label)), ...
    1, 5, features, {'bds-production-500n', competitor_solver_label});
assert_workflow_contract(fullfile(workflow_dir, sprintf( ...
    'profile_bds_%s_big_s2mpj.yml', competitor_file_label)), ...
    6, 50, features, {'bds-production-500n', competitor_solver_label});

end

function assert_nomad_runtime_linking(workflow_dir)

for size_name = {'small', 'big'}
    workflow_path = fullfile(workflow_dir, sprintf( ...
        'profile_bds_nomad_%s_s2mpj.yml', size_name{1}));
    workflow_text = fileread(workflow_path);
    assert(contains(workflow_text, 'bin/glnxa64/libmex.so'));
    assert(contains(workflow_text, 'bin/glnxa64/libmx.so'));
    assert(contains(workflow_text, 'bin/glnxa64/libut.so'));
    assert(contains(workflow_text, ...
        'extern/bin/glnxa64/libMatlabEngine.so'));
    assert(contains(workflow_text, ...
        ['bin/glnxa64:$matlab_root/extern/bin/glnxa64:', ...
        '$matlab_root/sys/os/glnxa64']));
    assert(contains(workflow_text, ...
        "ldd nomad/build/release/lib/nomadOpt.mexa64 | grep -q 'not found'"));
    setup_position = strfind(workflow_text, '- name: Set up Nomad');
    preload_position = strfind(workflow_text, '- name: Set LD_PRELOAD');
    runtime_position = strfind(workflow_text, ...
        '- name: Set MATLAB runtime library path');
    linking_position = strfind(workflow_text, ...
        '- name: Verify Nomad runtime linking');
    assert(isscalar(setup_position) && isscalar(preload_position) ...
        && isscalar(runtime_position) && isscalar(linking_position));
    assert(setup_position < preload_position ...
        && preload_position < runtime_position ...
        && runtime_position < linking_position);
end

end

function assert_workflow_contract( ...
        workflow_path, mindim, maxdim, expected_features, solver_names)

assert(isfile(workflow_path), 'Missing workflow: %s', workflow_path);
workflow_text = fileread(workflow_path);

assert(contains(workflow_text, sprintf('options.mindim = %d;', mindim)));
assert(contains(workflow_text, sprintf('options.maxdim = %d;', maxdim)));
uses_literal_s2mpj = contains(workflow_text, "options.plibs = 's2mpj';");
uses_s2mpj_matrix = contains(workflow_text, 'plibs: [s2mpj]') ...
    && contains(workflow_text, "options.plibs = '${{ matrix.plibs }}';");
assert(uses_literal_s2mpj || uses_s2mpj_matrix);
assert(contains(workflow_text, "setup(struct('install_matcutest', false));"));
assert(~contains(workflow_text, 'options.dim'));
assert(contains(workflow_text, expected_features));
assert(contains(workflow_text, 'workflow_dispatch:'));
assert(~contains(workflow_text, 'schedule:'));
assert(contains(workflow_text, 'merge_artifacts:'));
assert(contains(workflow_text, 'actions/download-artifact@v4'));
assert(sum(count(workflow_text, 'actions/upload-artifact@v4')) == 3);

feature_lines = regexp(workflow_text, ...
    '(?m)^\s*feature:\s*\[[^\n]+\]\s*$', 'match');
assert(numel(feature_lines) == 1);
assert(contains(feature_lines{1}, expected_features));

for i_solver = 1:numel(solver_names)
    assert(count(workflow_text, solver_names{i_solver}) == 1, ...
        'Expected exactly one use of solver label %s in %s.', ...
        solver_names{i_solver}, workflow_path);
end

end
